#!/usr/bin/env bash

set -euo pipefail

ROOT="${SUPABASE_REPO_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
SCHEMA="${1:-}"

if [[ ! "$SCHEMA" =~ ^[a-z][a-z0-9_]*$ ]]; then
  echo "usage: bun run supabase:configure -- <lowercase_schema_name>" >&2
  echo "Schema names must match ^[a-z][a-z0-9_]*$." >&2
  exit 1
fi

case "$SCHEMA" in
  auth | extensions | graphql_public | public | realtime | storage)
    echo "'$SCHEMA' is reserved by Supabase; choose an app-specific schema." >&2
    exit 1
    ;;
esac

TYPES="$ROOT/src/lib/supabase/database-generated.types.ts"
if [[ -f "$TYPES" ]] && ! grep -q "PLACEHOLDER GENERATED TYPES" "$TYPES"; then
  echo "Refusing to rename a schema after real generated database types exist." >&2
  exit 1
fi

mkdir -p "$ROOT/supabase/migrations" "$ROOT/src/lib/supabase"

write_atomic() {
  local destination="$1" temporary
  temporary=$(mktemp "${destination}.XXXXXX")
  cat > "$temporary"
  chmod 0644 "$temporary"
  mv "$temporary" "$destination"
}

write_atomic "$ROOT/supabase/project.env" <<EOF
# One lowercase Postgres identifier. Treat it as immutable after the database is connected.
SUPABASE_SCHEMA=$SCHEMA

# self_hosted reads postgres-meta in the shared stack; local reads Supabase CLI containers.
SUPABASE_TYPES_SOURCE=self_hosted
EOF

write_atomic "$ROOT/supabase/config.toml" <<EOF
project_id = "$SCHEMA"

[api]
enabled = true
port = 54321
schemas = ["$SCHEMA", "graphql_public"]
extra_search_path = ["public", "extensions"]
max_rows = 1000
auto_expose_new_tables = false

[db]
port = 54322
shadow_port = 54320
major_version = 17

[db.migrations]
enabled = true
schema_paths = []

[db.seed]
enabled = false
sql_paths = []

[realtime]
enabled = true

[studio]
enabled = true
port = 54323

[inbucket]
enabled = true
port = 54324

[storage]
enabled = true
file_size_limit = "50MiB"

[auth]
enabled = true
site_url = "http://127.0.0.1:5173"
additional_redirect_urls = ["http://localhost:5173", "http://127.0.0.1:5173"]
jwt_expiry = 3600
EOF

write_atomic "$ROOT/src/lib/supabase/database-schema.generated.ts" <<EOF
// GENERATED by bun run supabase:configure -- <schema>.
export const databaseSchema = '$SCHEMA';
EOF

write_atomic "$TYPES" <<EOF
// PLACEHOLDER GENERATED TYPES - replaced by bun run gen:types after the database is ready.
// Do not add application tables here by hand.

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  $SCHEMA: {
    Tables: {};
    Views: {};
    Functions: {};
    Enums: {};
    CompositeTypes: {};
  };
};
EOF

write_atomic "$ROOT/supabase/migrations/00000000000000_bootstrap_app_schema.sql" <<EOF
begin;

create schema if not exists $SCHEMA;

revoke all on schema $SCHEMA from public;
revoke all on schema $SCHEMA from anon;
grant usage on schema $SCHEMA to authenticated;
grant all on schema $SCHEMA to service_role;

alter default privileges for role postgres in schema $SCHEMA revoke execute on functions from public;
alter default privileges for role postgres in schema $SCHEMA grant all on tables to service_role;
alter default privileges for role postgres in schema $SCHEMA grant all on sequences to service_role;
alter default privileges for role postgres in schema $SCHEMA grant all on functions to service_role;

commit;

-- Grant authenticated or anon access per object in later migrations, after enabling RLS and
-- adding ownership policies. Do not add broad anonymous defaults here.
EOF

echo "Configured Supabase schema '$SCHEMA'."
echo "Next: start/reset locally, or apply the bootstrap migration to the self-hosted database."

FORMATTER="$(cd "$(dirname "$0")/.." && pwd)/node_modules/.bin/oxfmt"
if [[ -x "$FORMATTER" ]]; then
  "$FORMATTER" -c "$(cd "$(dirname "$0")/.." && pwd)/.oxfmtrc.jsonc" \
    "$ROOT/src/lib/supabase/database-schema.generated.ts" \
    "$ROOT/src/lib/supabase/database-generated.types.ts" >/dev/null
fi
